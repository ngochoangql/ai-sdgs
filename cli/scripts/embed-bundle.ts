import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeLf, toPosixPath, walkFiles } from '../src/core/crypto-fs.ts';
import { RELEASE_ID, STANDARD_VERSION } from '../src/core/constants.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../..');
const OUT_FILE = path.resolve(__dirname, '../src/generated/embedded-bundle.ts');

const BUNDLE_DIRS = ['standard', 'schemas', 'policies', 'templates', 'adapters'] as const;

const filesMap: Record<string, string> = {};

for (const dirName of BUNDLE_DIRS) {
  const absDir = path.join(REPO_ROOT, dirName);
  for (const absFile of walkFiles(absDir)) {
    const rel = toPosixPath(path.relative(REPO_ROOT, absFile));
    filesMap[rel] = normalizeLf(fs.readFileSync(absFile, 'utf8'));
  }
}

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
const tsContent = `// AUTO-GENERATED BY cli/scripts/embed-bundle.ts — DO NOT EDIT MANUALLY
export const EMBEDDED_STANDARD_VERSION = ${JSON.stringify(STANDARD_VERSION)};
export const EMBEDDED_RELEASE_ID = ${JSON.stringify(RELEASE_ID)};
export const EMBEDDED_BUNDLE_FILES: Readonly<Record<string, string>> = ${JSON.stringify(filesMap, null, 2)};
`;

fs.writeFileSync(OUT_FILE, tsContent, 'utf8');
console.log(`Embedded ${Object.keys(filesMap).length} files into ${OUT_FILE}`);
